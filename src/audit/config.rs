/// Generated by packages on install; not anyone's configuration.
fn generated_by_packages(path: &str) -> bool {
    let rest = path.strip_prefix("/etc/").unwrap_or(path);
    [
        "apparmor.d/local/",
        "apparmor.d/tunables/",
        "console-setup/",
        "xml/",
        "lvm/archive/",
        "lvm/backup/",
        "pam.d/common-",
        "multipath/",
        "pollinate/",
    ]
    .iter()
    .any(|p| rest.starts_with(p))
        || [
            "iscsi/initiatorname.iscsi",
            "security/opasswd",
            "python3/debian_config",
            "network/fan",
            "networks",
            "shells",
            "locale.gen",
            "locale.conf",
            "default/keyboard",
            "default/console-setup",
            "default/locale",
        ]
        .contains(&rest)
        || [".ucf-dist", ".ucf-old", ".ucf-new", ".dpkg-old", ".dpkg-dist"].iter().any(|s| path.ends_with(s))
}

fn stale_copy(path: &str) -> bool {
    [".old", ".bak", ".orig", "~", ".pre-moi"].iter().any(|s| path.ends_with(s))
}

/// `/etc` files and directories that the owner's units, cron jobs and scripts read: restore puts these
/// back with them. A file in its own directory (`/etc/host-firewall/rules4.txt`) means the directory.
pub(crate) fn referenced_etc(view: &View<'_>) -> Vec<String> {
    let mut sources: Vec<String> = view.custom_units();
    sources.push("/etc/crontab".to_string());
    sources.extend(view.captured_in("/etc/cron.d"));
    sources.extend(view.lines("scripts/index.txt"));
    let mut out = BTreeSet::new();
    for source in sources {
        let Some(text) = view.file(&source) else { continue };
        for line in text.lines().filter(|l| !l.trim_start().starts_with('#')) {
            let mut rest = line;
            while let Some(i) = rest.find("/etc/") {
                let before_ok = i == 0 || !rest[..i].ends_with(|c: char| c.is_alphanumeric() || "_.-".contains(c));
                let candidate = &rest[i..];
                let len =
                    candidate.find(|c: char| !(c.is_alphanumeric() || "_.@+-/".contains(c))).unwrap_or(candidate.len());
                let path = candidate[..len].trim_end_matches(['.', '/']);
                rest = &candidate[len.max(5)..];
                if !before_ok || !view.captured(path) || HANDLED.iter().chain(&GENERATED).any(|h| under(path, h)) {
                    continue;
                }
                let dir = path.rsplit_once('/').map_or("", |(d, _)| d);
                let own_dir =
                    dir.matches('/').count() >= 2 && !["/etc/default", "/etc/systemd", "/etc/security"].contains(&dir);
                out.insert(if own_dir { dir.to_string() } else { path.to_string() });
            }
        }
    }
    let all: Vec<String> = out.into_iter().collect();
    all.iter().filter(|p| !all.iter().any(|other| other != *p && under(p, other))).cloned().collect()
}

pub(super) fn section(view: &View<'_>, config: &Config, live: &Live) -> Section {
    let mut s = Section::new("config", "Configuration a restore would not put back");
    let host = view.host();
    let referenced = referenced_etc(view);
    let restored = |path: &str| {
        HANDLED.iter().any(|h| under(path, h))
            || config.restore.etc_paths.iter().any(|p| under(path, p))
            || referenced.iter().any(|r| under(path, r))
    };
    if !referenced.is_empty() {
        s.ok(format!(
            "read by your units, cron jobs and scripts, so restored with them: {}",
            referenced.iter().map(|p| format!("`{p}`")).collect::<Vec<_>>().join(", ")
        ));
    }

    // files no package owns, changed since the OS was installed
    if live.package_owned.is_empty() {
        s.info("package ownership is unknown on this system (no dpkg file lists), so custom files in /etc cannot be told apart");
    } else {
        let walk = Walk { skip_paths: GENERATED.iter().map(ToString::to_string).collect(), ..Walk::default() };
        let untouched_until = live.installed.map(|t| t + Duration::from_secs(86_400));
        let (mut custom, mut stale) = (Vec::new(), Vec::new());
        for file in walk_files(host, Path::new("/etc"), &walk) {
            let path = file.display().to_string();
            let Ok(md) = host.symlink_metadata(&file) else { continue };
            if md.kind != FileKind::File
                || live.package_owned.contains(&path)
                || generated_by_packages(&path)
                || restored(&path)
            {
                continue;
            }
            if untouched_until.is_some_and(|limit| md.mtime <= limit) {
                continue;
            }
            if stale_copy(&path) { stale.push(path) } else { custom.push(path) }
        }
        if !custom.is_empty() {
            s.gap(format!(
                "{} custom file(s) in /etc that no package owns and no restore phase puts back — add the ones that matter to `restore.etc_paths`:",
                custom.len()
            ));
            s.code(&custom, 120);
        }
        if !stale.is_empty() {
            s.review(format!(
                "stale copies in /etc (probably safe to delete): {}",
                stale.iter().map(|p| format!("`{p}`")).collect::<Vec<_>>().join(", ")
            ));
        }
    }

    // package config files the owner changed
    let mut modified = Vec::new();
    for (path, shipped) in &live.conffiles {
        if !path.starts_with("/etc/") || GENERATED.iter().any(|g| under(path, g)) {
            continue;
        }
        let Ok(data) = host.read(Path::new(path)) else { continue };
        let actual: String = Md5::digest(&data).iter().map(|b| format!("{b:02x}")).collect();
        if actual != *shipped {
            modified.push(path.clone());
        }
    }
    modified.sort();
    modified.dedup();
    for path in &modified {
        if restored(path) {
            s.ok(format!("`{path}` differs from the version its package ships; it is put back by the restore (in `restore.etc_paths` or another phase)"));
        } else if config.restore.restore_modified_conffiles {
            s.ok(format!("`{path}` differs from the version its package ships; the restore puts it back (`restore_modified_conffiles`, showing the diff)"));
        } else {
            s.gap(format!("`{path}` differs from the version its package ships and nothing restores it (`restore_modified_conffiles = false`)"));
        }
    }
    s.or_nothing("nothing")
}
